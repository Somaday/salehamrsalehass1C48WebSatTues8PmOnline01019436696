const image = (id) =>
  `https://images.unsplash.com/photo-${id}?w=800&h=400&fit=crop`;
const avatar = (id) =>
  `https://images.unsplash.com/photo-${id}?w=100&h=100&fit=crop&crop=face`;

function normalize(post) {
  return {
    ...post,
    content: post.content || post.excerpt,
    tags: post.tags || [post.category],
    author:
      typeof post.author === "object"
        ? post.author
        : {
            name: post.author,
            role: post.authorRole,
            avatar: post.authorAvatar,
          },
  };
}

const makePost = ([
  id,
  title,
  excerpt,
  category,
  author,
  role,
  authorId,
  date,
  readTime,
  imageId,
]) =>
  normalize({
    id,
    title,
    excerpt,
    category,
    author: { name: author, role, avatar: avatar(authorId) },
    date,
    readTime,
    image: image(imageId),
  });

